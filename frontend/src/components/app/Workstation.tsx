function LogicCanvas({ price, nodes: initial, onTopUp }: ToolProps & { nodes: Node[] }) {
  const qc = useQueryClient();
  const [nodes, setNodes] = useState(initial);
  const [prompt, setPrompt] = useState("");
  const add = useToolRun(onTopUp);
  const save = useMutation({
    mutationFn: (next: Node[]) =>
      api("/workstation/canvas", { method: "PUT", body: { nodes: next } }),
    onSuccess: (_d, next) =>
      qc.setQueryData<State>(["workstation"], (s) => (s ? { ...s, canvas: next } : s)),
    onError: hzToast.fromError,
  });
  return (
    <div className="card-duo flex flex-col gap-5 p-5">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <div className="font-display text-base font-bold">Logic Canvas</div>
          <p className="text-xs text-muted-foreground">
            Describe a step and it's added to your diagram. Saved automatically.
          </p>
        </div>
        <form
          onSubmit={(e) => {
            e.preventDefault();
            if (prompt.trim().length < 3) return;
            add.mutate(
              { action: "logic_canvas", prompt },
              {
                onSuccess: (r) => {
                  setNodes(r.output.nodes);
                  qc.setQueryData<State>(["workstation"], (s) =>
                    s ? { ...s, canvas: r.output.nodes } : s,
                  );
                  setPrompt("");
                },
              },
            );
          }}
          className="flex w-full max-w-lg items-center gap-2.5"
        >
          <input
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            maxLength={200}
            aria-label="Describe a flowchart step"
            placeholder="If the payment webhook times out after 5s…"
            className="min-w-0 flex-1 rounded-xl border border-border bg-muted/40 px-3.5 py-2.5 text-xs outline-none focus:border-primary"
          />
          <button
            disabled={add.isPending || prompt.trim().length < 3}
            className="btn-duo shrink-0 !py-2.5 !px-4 text-xs disabled:opacity-50"
          >
            {add.isPending ? <ButtonSpinner /> : <Plus className="h-3.5 w-3.5" />} Add node (
            {price("logic_canvas")})
          </button>
        </form>
      </div>
      <div className="min-h-[220px] overflow-x-auto rounded-2xl border border-border bg-[radial-gradient(var(--border)_1px,transparent_1px)] [background-size:18px_18px] p-5">
        <div className="flex flex-wrap items-center gap-3">
          {nodes.map((n, i) => (
            <div key={n.id} className="flex items-center gap-3">
              <div className="group relative min-w-[170px] rounded-2xl border-2 border-primary/40 bg-card p-3.5 shadow-md">
                <div className="flex items-center justify-between gap-2">
                  <span
                    className={`rounded-full px-2 py-0.5 font-mono text-[10px] font-bold uppercase ${KIND_TONE[n.kind]}`}
                  >
                    {n.kind}
                  </span>
                  <button
                    type="button"
                    aria-label={`Remove ${n.label}`}
                    onClick={() => {
                      const next = nodes.filter((x) => x.id !== n.id);
                      setNodes(next);
                      save.mutate(next);
                    }}
                    className="rounded p-0.5 text-muted-foreground opacity-0 transition-opacity hover:text-red-500 group-hover:opacity-100 focus:opacity-100"
                  >
                    <Trash2 className="h-3.5 w-3.5" />
                  </button>
                </div>
                <div className="mt-2 font-display text-xs font-bold leading-snug">{n.label}</div>
              </div>
              {i < nodes.length - 1 && <ArrowRight className="h-5 w-5 shrink-0 text-primary" />}
            </div>
          ))}
          {nodes.length === 0 && (
            <p className="text-sm text-muted-foreground">
              Empty canvas. Describe your first step above.
            </p>
          )}
        </div>
      </div>
    </div>
  );
}

