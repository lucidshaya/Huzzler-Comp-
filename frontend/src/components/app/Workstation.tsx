function useRun() {
  const qc = useQueryClient();
  const [topUp, setTopUp] = useState(false);
  const m = useMutation({
    mutationFn: (body: Record<string, unknown>) =>
      api<{ output: any; engine: "ai" | "mock"; cost: number; balance: number }>(
        "/workstation/run",
        { body },
      ),
    onSuccess: (r) => {
      qc.setQueryData<State>(["workstation"], (s) => (s ? { ...s, balance: r.balance } : s));
      void qc.invalidateQueries({ queryKey: ["wallet"] });
      hzToast.success(
        `−${r.cost} tokens`,
        r.engine === "ai"
          ? "Generated by Huzzler AI."
          : "Generated offline (AI key not connected yet).",
      );
    },
    onError: (err) => {
      if (err instanceof ApiError && err.code === "INSUFFICIENT_TOKENS") setTopUp(true);
      hzToast.fromError(err);
    },
  });
  return { ...m, topUp, setTopUp };
}

