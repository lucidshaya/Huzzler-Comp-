function VoiceStudio({ price, onTopUp }: ToolProps) {
  const qc = useQueryClient();
  const [transcript, setTranscript] = useState("");
  const [listening, setListening] = useState(false);
  const [digest, setDigest] = useState<{ shipped: string; today: string; blockers: string } | null>(
    null,
  );
  const sum = useToolRun(onTopUp);
  const post = useMutation({
    mutationFn: () =>
      api("/checkins", {
        body: {
          yesterday: digest!.shipped.slice(0, 1000),
          today: digest!.today.slice(0, 1000),
          blockers: /^none\.?$/i.test(digest!.blockers.trim())
            ? undefined
            : digest!.blockers.slice(0, 1000),
        },
      }),
    onSuccess: () => {
      void qc.invalidateQueries({ queryKey: ["workspace"] });
      hzToast.success("Stand-up posted", "Your squad and PM can see it.");
    },
    onError: hzToast.fromError,
  });
  // Browser speech recognition where available (Chrome, Edge, Safari); typing always works.
  const SR =
    typeof window !== "undefined"
      ? ((window as any).SpeechRecognition ?? (window as any).webkitSpeechRecognition)
      : null;
  const record = () => {
    if (!SR)
      return hzToast.info("Recording isn't supported in this browser", "Type your update instead.");
    const rec = new SR();
    rec.lang = "en-NG";
    rec.interimResults = false;
    rec.onresult = (e: any) =>
      setTranscript((t) =>
        `${t} ${Array.from(e.results)
          .map((r: any) => r[0].transcript)
          .join(" ")}`.trim(),
      );
    rec.onend = () => setListening(false);
    rec.onerror = () => setListening(false);
    setListening(true);
    rec.start();
  };
  return (
    <div className="grid grid-cols-1 gap-5 lg:grid-cols-12">
      <div className="card-duo flex flex-col gap-4 p-5 lg:col-span-6">
        <div className="flex items-center gap-3">
          <div
            className={`grid h-10 w-10 place-items-center rounded-xl ${listening ? "animate-pulse bg-[color:var(--fire)]/15 text-[color:var(--fire)]" : "bg-primary/10 text-primary"}`}
          >
            <Mic className="h-5 w-5" />
          </div>
          <div>
            <div className="font-display text-base font-bold">Stand-up recorder</div>
            <div className="text-xs text-muted-foreground">Speak or type your daily update</div>
          </div>
        </div>
        <textarea
          rows={5}
          value={transcript}
          onChange={(e) => setTranscript(e.target.value)}
          maxLength={4000}
          aria-label="Your stand-up update"
          placeholder="Yesterday I finished the filter hook. Today I'm wiring it into the grid. I'm waiting on the API contract."
          className="rounded-xl border border-border bg-muted/30 p-3.5 text-sm outline-none focus:border-primary"
        />
        <div className="flex flex-wrap gap-2.5">
          <button
            type="button"
            onClick={record}
            disabled={listening}
            className="btn-duo-outline !py-2 !px-4 text-xs"
          >
            <Mic className="h-3.5 w-3.5" /> {listening ? "Listening…" : "Record"}
          </button>
          <button
            type="button"
            disabled={sum.isPending || transcript.trim().length < 10}
            onClick={() =>
              sum.mutate(
                { action: "voice_summary", transcript },
                { onSuccess: (r) => setDigest(r.output) },
              )
            }
            className="btn-duo flex-1 !py-2 !px-4 text-xs disabled:opacity-50"
          >
            {sum.isPending ? <ButtonSpinner /> : <Sparkles className="h-3.5 w-3.5" />} Summarise (
            {price("voice_summary")})
          </button>
        </div>
      </div>
      <div className="card-duo flex flex-col gap-3 p-5 lg:col-span-6">
        <div className="font-display text-base font-bold">Stand-up summary</div>
        {digest ? (
          <>
            {(
              [
                ["✓ Shipped", digest.shipped, "text-primary"],
                ["→ Next up", digest.today, "text-[color:var(--gold)]"],
                ["⚡ Blockers", digest.blockers, "text-muted-foreground"],
              ] as const
            ).map(([label, text, cls]) => (
              <div
                key={label}
                className="rounded-xl border border-border bg-muted/30 p-3.5 text-xs"
              >
                <div className={`text-[10px] font-bold uppercase tracking-wider ${cls}`}>
                  {label}
                </div>
                <div className="mt-1">{text}</div>
              </div>
            ))}
            <button
              type="button"
              disabled={post.isPending}
              onClick={() => post.mutate()}
              className="btn-duo mt-1 !py-2 text-xs"
            >
              {post.isPending ? <ButtonSpinner /> : <Send className="h-3.5 w-3.5" />} Post as
              today's check-in
            </button>
          </>
        ) : (
          <p className="text-sm text-muted-foreground">
            Summarise an update to turn it into a stand-up you can post to your squad.
          </p>
        )}
      </div>
    </div>
  );
}
